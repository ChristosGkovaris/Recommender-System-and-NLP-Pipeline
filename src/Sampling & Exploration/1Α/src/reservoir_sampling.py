"""**Περιγραφή Αλγορίθμου Reservoir Sampling για Κ δείγματα:**

Ο αλγόριθμος διατηρεί έναν πίνακα μεγέθους **Κ**, που αρχικά γεμίζει με τα πρώτα Κ στοιχεία του ρεύματος.

Για κάθε επόμενο στοιχείο στη θέση **i** (ξεκινώντας από **i = K+1**), παράγει έναν τυχαίο αριθμό **j** μεταξύ 1 και **i**. Αν **j ≤ K**, τότε το αντικείμενο αντικαθιστά το στοιχείο της θέσης **j** του δείγματος. Έτσι, κάθε στοιχείο του ρεύματος έχει τελικά πιθανότητα **Κ/N** να βρίσκεται στο δείγμα, χωρίς να χρειάζεται να γνωρίζουμε εκ των προτέρων το **Ν**.

Ο αλγόριθμος απαιτεί μνήμη **O(K)** και διατρέχει το ρεύμα μία φορά.
"""

import random

# Reservoir Sampling: select K random lines from a file stream
def sample(filename, K):
    sample_list = []
    with open(filename, 'r', encoding='utf-8') as f:
        for i, line in enumerate(f):
            if i == 0:
                continue
            if len(sample_list) < K:
                sample_list.append(line.strip())
            else:
                j = random.randint(0, i)
                if j < K:
                    sample_list[j] = line.strip()
    return sample_list

# Path to CSV file in Google Drive
filename = '/content/input-A.csv'

# Sample size
K = 10

# Execution
sample_lines = sample(filename, K)

# Results
print("Random 10-line sample:\n")
for line in sample_lines:
    print(line)

"""**Αντιστοίχιση περιγραφής και κώδικα:**

Οι γραμμές **if len(sample_list) < K** υλοποιούν το βήμα όπου αποθηκεύονται τα πρώτα Κ στοιχεία.

Οι γραμμές **j = random.randint(0, i)** και **if j < K** αντιστοιχούν στην επιλογή με πιθανότητα **Κ/i**.

Η χρήση του **enumerate(f)** εξασφαλίζει ότι το αρχείο διαβάζεται γραμμή προς γραμμή, χωρίς να χρειάζεται η γνώση του συνολικού Ν.

Ο αλγόριθμος χρησιμοποιεί **Ο(Κ)** μνήμη, καθώς διατηρεί μόνο το δείγμα.

**Απόδειξη ομοιόμορφης δειγματοληψίας:**

Για τα πρώτα **Κ** στοιχεία, η πιθανότητα να βρίσκονται στο δείγμα είναι **1**. Για κάθε επόμενο στοιχείο στη θέση **i > K**, το στοιχείο επιλέγεται με πιθανότητα **K/i**.

Αν επιλεγεί, αντικαθιστά ένα από τα **Κ** τρέχοντα δείγματα. Για οποιοδήποτε στοιχείο **j ≤ i**, η πιθανότητα να παραμείνει στο δείγμα αφού περάσει το στοιχείο **i** είναι: **P(μένει) = 1 − (K/i) × (1/K) = 1 − 1/i**

Επαναλαμβάνοντας για όλα τα **i** από **K+1** έως **N**, η τελική πιθανότητα να βρίσκεται κάθε στοιχείο στο δείγμα είναι **K/N**.

Άρα ο αλγόριθμος είναι **ομοιόμορφος**.
"""