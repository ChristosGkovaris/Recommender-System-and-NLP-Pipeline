# Build sparse user–item rating matrix
R_4 = csr_matrix((vals_4, (rows_4, cols_4)), shape=(n_users_4, n_movies_4))

# Initialize cache for item-to-users mapping
item_users_cache_4 = {}

# Define function to compute mean rating of a user
def user_mean_4(R, u):
    # Extract non-zero ratings of user u
    vals = R[u].data
    # Return zero if user has no ratings
    if len(vals) == 0:
        return 0
    # Return mean of user's ratings
    return vals.mean()

# Define function to get users who rated a given item
def item_users_4(R, m):
    return R[:, m].nonzero()[0]

# Define function to find top-k users similar to user u
def similar_users_4(R, u, m_users, k):
    # Return empty arrays if no users rated the item
    if len(m_users) == 0:
        return np.array([]), np.array([])

    # Extract rating vector of target user
    u_vec = R.getrow(u)
    # Extract rating vectors of other users
    others = R[m_users]

    # Compute dot products between users
    dots = others.dot(u_vec.T).toarray().flatten()

    # Compute norm of target user vector
    u_norm = np.sqrt(u_vec.multiply(u_vec).sum())
    # Compute norms of other user vectors
    o_norm = np.sqrt(others.multiply(others).sum(axis=1)).A.flatten()

    # Compute denominator for cosine similarity
    denom = u_norm * o_norm
    # Avoid division by zero
    denom[denom == 0] = 1e-9

    # Compute cosine similarities
    sims = dots / denom

    # Sort users by similarity descending
    idx = np.argsort(-sims)
    # Select top-k similar users
    top_users = m_users[idx][:k]
    # Select corresponding similarities
    top_sims  = sims[idx][:k]

    # Return top users and their similarities
    return top_users, top_sims

# Define function to compute weighted rating score
def compute_score_4(k_ratings, k_sims):
    # Return zero if no neighbor ratings exist
    if len(k_ratings) == 0:
        return 0
    # Return zero if all similarities are zero
    if np.all(k_sims == 0):
        return 0
    # Compute weighted average of ratings
    return np.dot(k_ratings, k_sims) / np.sum(k_sims)

# Define user-based collaborative filtering prediction function
def predict_ucf_4(u, m, k):
    # Convert user id to integer index
    u = int(u)
    # Convert item id to integer index
    m = int(m)

    # Cache users who rated item m
    if m not in item_users_cache_4:
        item_users_cache_4[m] = item_users_4(R_4, m)
    m_users = item_users_cache_4[m]

    # Fallback to user mean if item has no ratings
    if len(m_users) == 0:
        return user_mean_4(R_4, u)

    # Find top-k similar users
    top_users, top_sims = similar_users_4(R_4, u, m_users, k)

    # Extract ratings of top-k users for item m
    k_ratings = R_4[top_users, m].toarray().flatten()

    # Compute weighted prediction score
    val = compute_score_4(k_ratings, top_sims)
    # Clip prediction to valid rating range
    return np.clip(val, 0, 5)

