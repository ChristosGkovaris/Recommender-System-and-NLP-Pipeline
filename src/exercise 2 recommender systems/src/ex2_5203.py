R_item_dense_4 = R_4.toarray().T

# Initialize cache for item-to-users mapping
item_users_cache_4 = {}

# Define fast item-to-users lookup with caching
def item_users_fast_4(m):
    # Cache users who rated item m
    if m not in item_users_cache_4:
        item_users_cache_4[m] = R_4[:, m].nonzero()[0]
    # Return cached user indices
    return item_users_cache_4[m]

# Define batch UCF prediction function
def predict_all_ucf_v4(test_users_4, test_items_4, Ks_4):
    # Convert k values to numpy array
    Ks_4  = np.array(Ks_4)
    # Determine maximum k
    maxK_4 = Ks_4.max()
    # Number of test samples
    N_4 = len(test_users_4)

    # Initialize prediction matrix
    preds_4 = np.zeros((N_4, len(Ks_4)))
    # Get unique items in test set
    unique_movies_4 = np.unique(test_items_4)

    # Loop over each item
    for m in unique_movies_4:

        # Get indices of test rows for item m
        rows_idx_4 = np.where(test_items_4 == m)[0]
        # Extract corresponding users
        tu_4 = test_users_4[rows_idx_4]

        # Get users who rated item m
        m_users_4 = item_users_fast_4(m)

        # Handle items with no ratings
        if len(m_users_4) == 0:
            preds_4[rows_idx_4, :] = 0
            continue

        # Compute dot products between users and neighbors
        dots_4 = R_item_dense_4[tu_4][:, m_users_4]

        # Compute user norms
        u_norm_4 = user_norms_4[tu_4][:, None]
        # Compute neighbor norms
        o_norm_4 = user_norms_4[m_users_4][None, :]
        # Compute denominator for cosine similarity
        denom_4 = u_norm_4 * o_norm_4
        # Avoid division by zero
        denom_4[denom_4 == 0] = 1e-9

        # Compute cosine similarities
        sims_4 = dots_4 / denom_4

        # Get number of available neighbors
        L_4 = sims_4.shape[1]
        # Clamp effective k
        K_eff_4 = min(maxK_4, L_4)

        # Partially sort similarities to get top neighbors
        part_4 = np.argpartition(-sims_4, K_eff_4-1, axis=1)[:, :K_eff_4]

        # Build row indices for sorting
        row_idx_4 = np.arange(len(sims_4))[:, None]
        # Sort top neighbors by similarity
        order_4 = part_4[row_idx_4, np.argsort(-sims_4[row_idx_4, part_4], axis=1)]

        # Loop over each test row
        for r, ord_row in enumerate(order_4):

            # Extract neighbor similarities
            neigh_sims_4 = sims_4[r, ord_row]
            # Extract neighbor user indices
            neigh_users_4 = m_users_4[ord_row]

            # Extract neighbor ratings
            ratings_4 = R_item_dense_4[m, neigh_users_4]

            # Compute cumulative weighted ratings
            cum_w_4 = np.cumsum(ratings_4 * neigh_sims_4)
            # Compute cumulative similarity sums
            cum_s_4 = np.cumsum(neigh_sims_4)

            # Number of neighbors
            L2_4 = len(cum_s_4)

            # Loop over k values
            for j, k in enumerate(Ks_4):

                # Handle insufficient neighbors or zero similarity
                if k > L2_4 or cum_s_4[k-1] == 0:
                    preds_4[rows_idx_4[r], j] = 0
                # Compute weighted average prediction
                else:
                    preds_4[rows_idx_4[r], j] = cum_w_4[k-1] / cum_s_4[k-1]

    # Clip predictions to valid rating range
    return np.clip(preds_4, 0, 5)

